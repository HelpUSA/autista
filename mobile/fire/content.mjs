export const FIRE_MESSAGES=Object.freeze(translations);
export function normalizeFireLocale(locale){
  return FIRE_LOCALES.includes(locale)?locale:FIRE_DEFAULT_LOCALE;
}
export function fireText(locale,key){
  const text=translations[normalizeFireLocale(locale)][key];
  if(typeof text!=='string'||!text.trim())throw new Error('Missing Fire translation: '+key);
  return text;
}
